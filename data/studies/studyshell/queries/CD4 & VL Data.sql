SELECT ParticipantVisit.ParticipantId,
ParticipantVisit.SequenceNum,
ClinicalData.GroupAssigned,
ClinicalData.age,
ClinicalData.gender,
ClinicalData.race,
ClinicalData.tribe,
ClinicalData.EnrollmentDt,
ClinicalData.SpecCollDt,
ClinicalData.initialFiebigStage AS "Initial Fiebig Stage",
v.setpoint,
ClinicalData.AltCollDtVirLd,
ClinicalData.VirLdModifier,
ClinicalData.VirLdValue,
ClinicalData.AltCollDtVirLd2,
ClinicalData.VirLdModifier2,
ClinicalData.VirLdValue2,
ClinicalData.AltCollDtAbsCD4,
ClinicalData.AbsCD4,
ClinicalData.DtART,
ClinicalData.ART,
ParticipantVisit."AL-1".AL1stdt AS ARTMed1Start,
ParticipantVisit."AL-1".AL1spdt AS ARTMed1Stop,
ParticipantVisit."AL-1".AL2stdt AS ARTMed2Start,
ParticipantVisit."AL-1".AL2spdt AS ARTMed2Stop,
ParticipantVisit."AL-1".AL3stdt AS ARTMed3Start,
ParticipantVisit."AL-1".AL3spdt AS ARTMed3Stop,
ParticipantVisit."AL-1".AL4stdt AS ARTMed4Start,
ParticipantVisit."AL-1".AL4spdt AS ARTMed4Stop,
ParticipantVisit."AL-1".AL5stdt AS ARTMed5Start,
ParticipantVisit."AL-1".AL5spdt AS ARTMed5Stop
FROM ParticipantVisit
LEFT JOIN ClinicalData ON ParticipantVisit.ParticipantId=ClinicalData.ParticipantId AND ParticipantVisit.SequenceNum=ClinicalData.SequenceNum
LEFT JOIN study."Viral Load Set Point" v ON ParticipantVisit.ParticipantId=v.ParticipantId AND ParticipantVisit.SequenceNum=v.SequenceNum
ORDER BY ParticipantVisit.ParticipantId,ParticipantVisit.sequencenum
